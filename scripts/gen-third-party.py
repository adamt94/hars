#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.txt: the licence of every crate in Cargo.lock.

    python3 scripts/gen-third-party.py

Run it after any change to Cargo.lock. `scripts/test_third_party.py` fails
when the file's crate list and Cargo.lock differ. The Docker image carries
the file in /licenses.

For each crate from a registry it records the name, version, licence
expression and repository, then prints every distinct licence text once,
with the crates it came from. The texts are read from the crate sources
that cargo has downloaded (`cargo fetch --locked` gets them).
"""

import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD-PARTY-LICENSES.txt"
# File names that hold a licence, a copyright notice or a NOTICE.
NAMES = ("license", "licence", "copying", "copyright", "notice", "unlicense")

HEADER = """\
Third-party Rust crates in hars

Generated by scripts/gen-third-party.py from Cargo.lock. Do not edit.

hars is built from the crates below. Each belongs to its authors and is
used under the licence named beside it. Every licence text that a crate
ships is reproduced below. The crates under [dev-dependencies] are listed
too, although they are not in the released binary. NOTICE covers everything
that is not a Rust crate.

"""


def packages():
    """Every registry package cargo resolves, sorted by name and version."""
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    found = [p for p in meta["packages"] if p["source"]]
    return sorted(found, key=lambda p: (p["name"], p["version"]))


def licence_files(package):
    """The licence texts in a crate's source directory, by file name."""
    folder = pathlib.Path(package["manifest_path"]).parent
    files = []
    for path in sorted(folder.iterdir()):
        if path.is_file() and path.name.lower().startswith(NAMES):
            text = path.read_text(encoding="utf-8", errors="replace")
            # Line ends and trailing space differ between copies of one text.
            lines = [line.rstrip() for line in text.strip().splitlines()]
            files.append((path.name, "\n".join(lines)))
    return files


def main():
    crates = packages()
    texts = {}  # digest -> (text, [crate labels])
    lines = [HEADER, "Crates\n------\n\n"]
    missing = []
    for p in crates:
        label = f"{p['name']} {p['version']}"
        licence = p.get("license") or "see the crate's licence file"
        lines.append(f"{label}\n  licence: {licence}\n")
        if p.get("repository"):
            lines.append(f"  source: {p['repository']}\n")
        files = licence_files(p)
        if not files:
            missing.append(label)
        for name, text in files:
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(digest, (text, []))[1].append(f"{label} ({name})")
    lines.append("\n\nLicence texts\n-------------\n")
    for text, users in sorted(texts.values(), key=lambda t: t[1][0]):
        lines.append("\n" + "=" * 76 + "\n")
        lines.append("Used by: " + ", ".join(users) + "\n")
        lines.append("=" * 76 + "\n\n")
        lines.append(text + "\n")
    OUT.write_text("".join(lines), encoding="utf-8")
    print(f"{OUT.name}: {len(crates)} crates, {len(texts)} licence texts")
    if missing:
        print("no licence file in the crate (expression only):", ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
