#!/usr/bin/env python3
"""Generate crates/ha-api/src/onboarding_data.rs from Home Assistant's wheel.

    scripts/gen-onboarding.py path/to/homeassistant-2026.6.1-py3-none-any.whl \
        > crates/ha-api/src/onboarding_data.rs

It writes what onboarding and `config/core/update` check against:

- `COUNTRIES`, `CURRENCIES` and `LANGUAGES`: the sets behind `cv.country`,
  `cv.currency` (`ACTIVE_CURRENCIES`) and `cv.language`
  (`generated/{countries,currencies,languages}.py`), sorted;
- `AREAS`: onboarding's `DEFAULT_AREAS` (`components/onboarding/const.py`),
  each with its icon and its name in every language that has an onboarding
  translation, English where a language lacks one, as
  `async_get_translations` falls back.
"""

import ast
import json
import re
import sys
import zipfile


def literal_set(source, name):
    """The set literal assigned to `name` in a generated module."""
    tree = ast.parse(source)
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            return sorted(ast.literal_eval(node.value))
    raise SystemExit(f"{name} not found")


def rust_list(name, doc, items):
    body = "\n".join(f'    "{i}",' for i in items)
    return f"/// {doc}\npub(crate) static {name}: &[&str] = &[\n{body}\n];\n"


def main(wheel):
    z = zipfile.ZipFile(wheel)
    read = lambda p: z.read(f"homeassistant/{p}").decode()
    countries = literal_set(read("generated/countries.py"), "COUNTRIES")
    currencies = literal_set(read("generated/currencies.py"), "ACTIVE_CURRENCIES")
    languages = literal_set(read("generated/languages.py"), "LANGUAGES")

    const = read("components/onboarding/const.py")
    defaults = re.findall(r'DefaultArea\(key="(\w+)", icon="([\w:-]+)"\)', const)
    assert len(defaults) == 3, defaults

    prefix = "homeassistant/components/onboarding/translations/"
    names = {}
    for path in sorted(n for n in z.namelist() if n.startswith(prefix)):
        lang = path[len(prefix) : -len(".json")]
        names[lang] = json.loads(z.read(path)).get("area", {})
    english = names["en"]
    rows = []
    for lang in sorted(names):
        row = [names[lang].get(key) or english[key] for key, _ in defaults]
        if lang != "en" and row == [english[key] for key, _ in defaults]:
            continue  # the same as the fallback
        rows.append((lang, row))

    def quoted(s):
        return json.dumps(s, ensure_ascii=False)

    out = [
        "// Generated by scripts/gen-onboarding.py from Home Assistant 2026.6.1's",
        "// wheel. Do not edit.",
        "",
        rust_list("COUNTRIES", "`cv.country`: ISO 3166 codes.", countries),
        rust_list("CURRENCIES", "`cv.currency`: active ISO 4217 codes.", currencies),
        rust_list("LANGUAGES", "`cv.language`: the languages HA knows.", languages),
        "/// Onboarding's `DEFAULT_AREAS`: (translation key, icon), in order.",
        "pub(crate) static AREA_KEYS: [(&str, &str); 3] = [",
        *[f'    ("{k}", "{i}"),' for k, i in defaults],
        "];",
        "",
        "/// Their names by language (`component.onboarding.area.*`), sorted by",
        "/// language; `en` is the fallback, and languages whose names are all",
        "/// English are left out.",
        "pub(crate) static AREA_NAMES: &[(&str, [&str; 3])] = &[",
        *[
            f'    ("{lang}", [{", ".join(quoted(n) for n in row)}]),'
            for lang, row in rows
        ],
        "];",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
