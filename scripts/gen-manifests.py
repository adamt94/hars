#!/usr/bin/env python3
"""Generate crates/ha-api/src/manifests_data.rs from Home Assistant's wheel.

    scripts/gen-manifests.py path/to/homeassistant-2026.6.1-py3-none-any.whl

`manifest/list` and `manifest/get` answer with each integration's
manifest.json as HA holds it (`Integration.manifest`: the file's keys in
order, then `is_built_in` and `overwrites_built_in`), serialized compactly
as HA's `json_bytes` does. Only the domains below are embedded, to keep the
binary small: what hars runs or will run, `default_config`'s
dependencies, and other integrations an imported install commonly has
config entries for (the frontend asks for those by name).

`integration/descriptions` answers with the entries of HA's
`generated/integrations.json` for the integrations a config flow can add:
`DESCRIPTIONS` holds, for each domain in `FLOW_DOMAINS` (described on its
own or inside a brand), the entry as HA sends it and whether the domain is
in `translated_name`.
"""

import json
import sys
import zipfile

DOMAINS = set(
    """api auth automation binary_sensor brands button climate config cover
    default_config device_tracker event fan frontend group history
    homeassistant http hue input_boolean labs lifx light lock logbook lovelace
    media_player met mobile_app mqtt notify number onboarding person
    persistent_notification recorder remote repairs scene script select sensor
    sun switch switchbot_cloud system_log vacuum weather websocket_api zone
    analytics backup shopping_list google_translate radio_browser tts
    """.split()
)

# What hars has a config flow for, or will next (docs/ROADMAP.md).
FLOW_DOMAINS = {"hue", "lifx", "switchbot_cloud"}


def main(wheel):
    z = zipfile.ZipFile(wheel)
    read = lambda d: json.loads(z.read(f"homeassistant/components/{d}/manifest.json"))
    domains = set(DOMAINS) | set(read("default_config")["dependencies"])
    out = [
        "// Generated by scripts/gen-manifests.py from Home Assistant 2026.6.1's",
        "// wheel. Do not edit.",
        "",
        "/// (domain, manifest JSON as HA serializes it), sorted by domain.",
        "pub(crate) const MANIFESTS: &[(&str, &str)] = &[",
    ]
    for d in sorted(domains):
        m = read(d)
        m["is_built_in"] = True
        m["overwrites_built_in"] = False
        text = json.dumps(m, separators=(",", ":"), ensure_ascii=False)
        assert '"#' not in text
        out.append(f'    ("{d}", r#"{text}"#),')
    out.append("];")
    listed = json.loads(z.read("homeassistant/generated/integrations.json"))
    described = {}
    for domain, item in listed["integration"].items():
        if "integration_type" in item:
            described[domain] = item
        for inner, description in item.get("integrations", {}).items():
            described[inner] = description
    out += [
        "",
        "/// (domain, its `integration/descriptions` entry, in `translated_name`),",
        "/// sorted by domain.",
        "pub(crate) const DESCRIPTIONS: &[(&str, &str, bool)] = &[",
    ]
    for d in sorted(FLOW_DOMAINS):
        text = json.dumps(described[d], separators=(",", ":"), ensure_ascii=False)
        assert '"#' not in text
        translated = "true" if d in listed["translated_name"] else "false"
        out.append(f'    ("{d}", r#"{text}"#, {translated}),')
    out.append("];")
    open("crates/ha-api/src/manifests_data.rs", "w").write("\n".join(out) + "\n")


main(sys.argv[1])
