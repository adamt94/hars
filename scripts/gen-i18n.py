#!/usr/bin/env python3
"""Generate crates/ha-api/src/i18n_data.rs from Home Assistant's wheel.

    scripts/gen-i18n.py path/to/homeassistant-2026.6.1-py3-none-any.whl

HA builds `translations/en.json` for each integration at release time (the
source tree only has `strings.json`), so the wheel is the source of truth.
For each domain below this writes, per (category, domain):

- translations: the body of the flattened object HA's translation cache
  makes (`"component.<domain>.<category>.<path>": "<string>"`, no braces),
  so a response is fragments joined with commas, with nothing parsed;
- icons: the category's JSON subtree, with shorthand service icons
  expanded as HA's `_load_icons_file` does.

Integrations without `title` get their manifest name, as HA does.
"""

import json
import sys
import zipfile

# What hars runs or will run (docs/ROADMAP.md), plus the core domains the
# frontend asks about. Others are answered with nothing.
DOMAINS = sorted(
    """api auth automation binary_sensor button climate config device_tracker
    event frontend group history homeassistant http hue input_boolean lifx
    light logbook lovelace met mobile_app notify onboarding person
    persistent_notification recorder repairs scene script sensor sun switch
    switchbot_cloud system_log vacuum weather websocket_api zone""".split()
)


def flatten(prefix, data, out):
    for key, value in data.items():
        if isinstance(value, dict):
            flatten(f"{prefix}{key}.", value, out)
        else:
            out[f"{prefix}{key}"] = value


def dumps(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def raw(s):
    assert '"###' not in s
    return f'r###"{s}"###'


def main(wheel):
    z = zipfile.ZipFile(wheel)
    names = set(z.namelist())

    def load(path):
        p = f"homeassistant/components/{path}"
        return json.loads(z.read(p)) if p in names else None

    translations, icons = [], []
    for domain in DOMAINS:
        manifest = load(f"{domain}/manifest.json")
        assert manifest, f"no integration {domain}"
        strings = load(f"{domain}/translations/en.json") or {}
        strings.setdefault("title", manifest["name"])
        for category, resource in strings.items():
            if isinstance(resource, dict):
                flat = {}
                flatten(f"component.{domain}.{category}.", resource, flat)
            else:
                flat = {f"component.{domain}.{category}": resource}
            if flat:
                translations.append((category, domain, dumps(flat)[1:-1]))
        for category, resource in (load(f"{domain}/icons.json") or {}).items():
            if category == "services":
                resource = {
                    k: {"service": v} if isinstance(v, str) else v
                    for k, v in resource.items()
                }
            icons.append((category, domain, dumps(resource)))

    out = [
        "// Generated by scripts/gen-i18n.py from Home Assistant 2026.6.1's",
        "// wheel. Do not edit. (category, domain, JSON), sorted.",
        "",
        "/// Flattened English translations: an object's body, no braces.",
        "pub(crate) static TRANSLATIONS: &[(&str, &str, &str)] = &[",
    ]
    out += [f'    ("{c}", "{d}", {raw(j)}),' for c, d, j in sorted(translations)]
    out += ["];", "", "/// `icons.json` subtrees.", "pub(crate) static ICONS: &[(&str, &str, &str)] = &["]
    out += [f'    ("{c}", "{d}", {raw(j)}),' for c, d, j in sorted(icons)]
    out += ["];", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
